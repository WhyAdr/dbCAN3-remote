#!/usr/bin/env python3
"""Regenerate contract documentation from the runtime registry."""
from __future__ import annotations
import argparse
from pathlib import Path
from dbcan_outcomes import REGISTRY

ROOT = Path(__file__).resolve().parents[1]


def recovery_table():
    lines = ['| Code | Kind | Sanctioned remediation | Forbidden workarounds |', '|---|---|---|---|']
    for code, info in REGISTRY.items():
        remedies = ' '.join(r['text'] for r in info['remediation']) or info['summary']
        banned = ' '.join(r['text'] for r in info['forbidden']) or '—'
        lines.append('| `%s` | %s | %s | %s |' % (code, info['kind'], remedies, banned))
    return '\n'.join(lines)


def generated_documents():
    return {ROOT/'docs/outcome-codes.md': '# Outcome codes (contract v1)\n\nGenerated by `scripts/gen_docs.py`; edit the runtime registry.\n\n'+recovery_table()+'\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated documents differ')
    args = parser.parse_args()
    stale = []
    for path, text in generated_documents().items():
        if not path.exists() or path.read_text() != text:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check: path.parent.mkdir(parents=True, exist_ok=True); path.write_text(text)
    if args.check and stale:
        parser.exit(1, 'stale generated docs: '+', '.join(stale)+'\n')

if __name__ == '__main__': main()
